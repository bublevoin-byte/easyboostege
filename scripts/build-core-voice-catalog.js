import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function expressionBetween(source, startMarker, endMarker) {
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker, start + startMarker.length);
  if (start < 0 || end < 0) throw new Error(`Catalog marker not found: ${startMarker}`);
  return source.slice(start + startMarker.length, end).trim().replace(/;$/u, '');
}

function literal(source, startMarker, endMarker) {
  return vm.runInNewContext(`(${expressionBetween(source, startMarker, endMarker)})`, Object.create(null), { timeout: 1_000 });
}

export function buildCoreVoiceCatalogSource() {
  const grammarSource = fs.readFileSync(path.join(root, 'public/screens/grammar.js'), 'utf8');
  const appSource = fs.readFileSync(path.join(root, 'public/app.js'), 'utf8');
  return {
    topics: literal(grammarSource, 'const G_TOPICS=', '\nconst G_BANK='),
    grammar: literal(grammarSource, 'const G_BANK=', '\nconst G_RINT='),
    exams: literal(grammarSource, 'const G_EXAMS=', '\ndecorateCoreGrammar(G_BANK,G_EXAMS);'),
    vocabulary: literal(appSource, 'const EGE_WORDS=', '\ndecorateCoreVocabulary(EGE_WORDS);'),
  };
}

export function renderCoreVoiceCatalog() {
  const source = JSON.stringify(buildCoreVoiceCatalogSource(), null, 2);
  return `// Generated by scripts/build-core-voice-catalog.js. Do not edit by hand.\n`
    + `export const CORE_VOICE_CATALOG_SOURCE = Object.freeze(${source});\n`;
}

const target = path.join(root, 'voice-tutor/generated-core-catalog.js');
const rendered = renderCoreVoiceCatalog();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== rendered) {
    process.stderr.write('Core Voice Tutor catalog is stale. Run: node scripts/build-core-voice-catalog.js\n');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(target, rendered, 'utf8');
  process.stdout.write(`Generated ${path.relative(root, target)}\n`);
}
