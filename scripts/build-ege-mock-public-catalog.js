import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

import {
  EGE_MOCK_FORM_ID,
  EGE_MOCK_FORM_REVISION,
  assertEgeMockForm,
  getEgeMockForm,
  getEgeMockPublicForm,
} from '../ege-mock/catalog.js';

const outputPath = fileURLToPath(new URL('../public/ege-mock-form-1-v1.js', import.meta.url));
assertEgeMockForm(getEgeMockForm(EGE_MOCK_FORM_ID, EGE_MOCK_FORM_REVISION));
const projection = getEgeMockPublicForm(EGE_MOCK_FORM_ID, EGE_MOCK_FORM_REVISION);
const source = `/* Generated by scripts/build-ege-mock-public-catalog.js. Do not edit by hand. */
function deepFreeze(value) {
  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;
  Object.values(value).forEach(deepFreeze);
  return Object.freeze(value);
}

export const EGE_MOCK_FORM_1_V1_PUBLIC = deepFreeze(${JSON.stringify(projection, null, 2)});
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== source) {
    console.error('public/ege-mock-form-1-v1.js is stale');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, source);
}
