const CODIFIER_AREA_BY_SLUG = new Map(Object.entries(CODIFIER_AREA_SLUGS).flatMap(
  ([area, slugs]) => slugs.map((slug) => [slug, area]),
));

function cefrFor(index) {
  if (index < 12) return 'B1';
  if (index < 48) return 'B2';
  return 'B2+/C1';
}

function completenessForQuestions() {
  return Array.from({ length: 5 }, (_, index) => ({
    questionNumber: index + 1,
    minimumSentences: 2,
    maximumSentences: 3,
    requiredElements: ['direct_answer', 'supporting_detail'],
  }));
}

function taskFromRow([slug, topic, questions], index) {
  return {
    id: `${SPEAKING_CATALOG_ID}.task3.${slug}`,
    revision: 1,
    taskType: 3,
    cefr: cefrFor(index),
    codifierArea: CODIFIER_AREA_BY_SLUG.get(slug),
    topic,
    preparationSeconds: 0,
    questionSeconds: 40,
    maxScore: 5,
    instruction: SPEAKING_TASK3_INSTRUCTION,
    questions,
    completeness: completenessForQuestions(),
    provenance: {
      kind: 'original', author: 'Easy Boost', createdAt: '2026-08-06', reviewStatus: 'automatically_checked',
    },
  };
}

